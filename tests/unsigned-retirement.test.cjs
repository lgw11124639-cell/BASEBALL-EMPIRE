const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const start=src.indexOf('function retireUnsignedReleasedPlayers('),end=src.indexOf('function releasedPlayerSigningDay(',start);
assert.ok(start>=0&&end>start,'unsigned retirement function exists');
const make=(id,level,year)=>({id,name:'Player '+id,age:27,teamId:0,level,releaseYear:year,faMarketSince:year,careerStats:{hits:123},teamHistory:[{year:2025,to:0}]});
const old=make(1,'방출',2026),recent=make(2,'방출',2027),fa=make(3,'FA대기',2026),signed=make(4,'2군',2026),foreign={...make(5,'방출',2026),foreignPlayer:true},noDate=make(6,'방출',undefined);
const state={year:2028,day:365,players:[old,recent,fa,signed,foreign,noDate],retiredPlayers:[]};
let notices=0;
const ctx=vm.createContext({state,Number,seasonDate:()=>new Date(2028,11,31),clubNotice:()=>notices++});
vm.runInContext(src.slice(start,end),ctx);
vm.runInContext('retireUnsignedReleasedPlayers()',ctx);
assert.equal(old.retired,true,'two-season unsigned player retires');
assert.equal(fa.retired,true,'two-season unsigned FA retires');
for(const p of [recent,signed,foreign,noDate])assert.notEqual(p.retired,true,'ineligible player remains active');
assert.equal(old.careerStats.hits,123,'career preserved');
assert.equal(old.teamHistory.length,1,'team history preserved');
assert.equal(state.retiredPlayers.length,2,'archived exactly two');
assert.equal(notices,2,'two retirement notices');
vm.runInContext('retireUnsignedReleasedPlayers()',ctx);
assert.equal(state.retiredPlayers.length,2,'no duplicate retirement');
assert.equal(notices,2,'no duplicate notices');
const releaseStart=src.indexOf('function recordPlayerRelease('),releaseEnd=src.indexOf('function publishReserveRoster(',releaseStart);
assert.ok(releaseStart>=0&&releaseEnd>releaseStart,'release recorder exists');
state.releaseNotices=[];
state.day=100;
vm.runInContext(src.slice(releaseStart,releaseEnd),ctx);
const newlyReleased={id:101,teamId:0,level:'방출',releaseYear:null};
vm.runInContext('recordPlayerRelease',ctx)(newlyReleased,'계약 종료');
assert.equal(newlyReleased.releaseYear,2028,'null legacy release year stamped');
vm.runInContext('recordPlayerRelease',ctx)(newlyReleased,'계약 종료');
assert.equal(state.releaseNotices.length,1,'release notice not duplicated');
const rereleased={id:102,teamId:0,level:'방출',releaseYear:2026};
vm.runInContext('recordPlayerRelease',ctx)(rereleased,'재방출');
assert.equal(rereleased.releaseYear,2028,'new release resets unsigned clock');
assert.equal(state.releaseNotices.length,2,'new release notice archived');


console.log('Unsigned player retirement after two seasons: PASS');
