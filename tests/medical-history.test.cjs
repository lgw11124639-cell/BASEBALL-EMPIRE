const assert=require('node:assert/strict'),vm=require('node:vm');
const c=require('./helpers/game-context.cjs')(),run=code=>vm.runInContext(code,c);
run(`state=world(0);state.year=2039;state.seasonStartDate='2039-01-01';state.day=202;const medicalPlayer=state.players.find(p=>p.position==='C');ensureProfile(medicalPlayer);beRecordMedicalInjury(medicalPlayer,'어깨 염좌',8,'경기 중 송구',30,{severity:'경상',surgery:false});`);
assert.equal(run('medicalPlayer.injuryHistory[0].occurredDate'),'2039-07-21');
const planned=run('medicalPlayer.injuryHistory[0].expectedReturnDate');assert.match(planned,/^2039-07-/);
const html=run('playerInjuryHistoryPanel(medicalPlayer)');
for(const text of ['2039년 7월 21일','경기 중 송구','복귀 예정일','수술 없음','당시 담당 트레이너','재활 관리'])assert.ok(html.includes(text),text);
assert.ok(!html.includes('일차'));
run(`medicalPlayer.profile.injury.days=1;state.day++;medicalRosterDay();`);
assert.equal(run('medicalPlayer.injuryHistory[0].recoveredDate'),'2039-07-22');
assert.match(run('playerInjuryHistoryPanel(medicalPlayer)'),/실제 이탈 기간/);
run(`state.year=2040;state.seasonStartDate='2040-01-01';state.day=20;`);
assert.ok(run('playerInjuryHistoryPanel(medicalPlayer)').includes('2039년 7월 21일'),'old injury keeps original calendar date after rollover');
run(`medicalPlayer.injuryHistory=[];medicalPlayer.profile.injury={type:'어깨',occurredDay:202,occurredYear:2039,days:0};`);
assert.ok(run('playerInjuryHistoryPanel(medicalPlayer)').includes('2039년 7월 21일'));
assert.ok(run('playerInjuryHistoryPanel(medicalPlayer)').includes('상세 정보가 보존되지 않았습니다'));
assert.equal(run("medicalCalendarISO(2028,61,'2028-01-01')"),'2028-03-01','leap-year dates');
assert.equal(run("medicalCalendarISO(2039,2,'2039-03-20')"),'2039-03-21','custom season anchor');
run(`medicalPlayer.profile.injury={type:'손목',days:0};`);
assert.ok(run('playerInjuryHistoryPanel(medicalPlayer)').includes('미기록'));
run("state.clubNotices=[];state.clubTransactionArchive={};medicalPlayer.profile.injury={type:'어깨',occurredDay:202,days:0}");
assert.ok(!run('playerInjuryHistoryPanel(medicalPlayer)').includes('2040년'),'unknown legacy year is not invented');
run("clubNotice('부상','어깨 부상','어깨 진단',[0],[medicalPlayer.id]);state.clubNotices[0].year=2038;state.clubNotices[0].day=202");
assert.ok(run('playerInjuryHistoryPanel(medicalPlayer)').includes('2038년 7월 21일'),'legacy date recovered from published injury notice');
console.log('PASS medical calendar dates, diagnosis, rehabilitation, recovery, old-save fallback and rollover');
