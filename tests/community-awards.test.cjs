const assert=require('node:assert/strict');
const vm=require('node:vm');
const c=require('./helpers/game-context.cjs')();
const run=s=>vm.runInContext(s,c);
run(`state=world(0);state.year=2030;state.day=1;state.seasonStartDate='2030-01-01';state.clubNotices=[];state.awards=[];kpblOffice();state.leagueOffice.governance.cases=[];var donors=state.players.filter(p=>!p.retired&&!p.draftPending&&['1군','2군','육성'].includes(p.level)).slice(0,5);for(const p of donors){p.salary=100000000;p.serviceYears=5;p.contractSigned=true;ensureProfile(p);p.profile.trait='팀워크 중심형';delete p.community;}var donor=donors[0];var originalSalary=donor.salary,originalBudget=state.teams.find(t=>t.id===donor.teamId).budget;`);
assert.equal(run('kpblCommunityAccount(donor).fund.balance'),0,'opening an account must not grant past wealth');
assert.equal(run("contributePlayerCommunity(donor,150000,'청소년 지원','receipt-1')"),null,'no donation before funds accrue');
run('state.day=32');
assert.ok(run('kpblCommunityAccount(donor).fund.balance')>=169000);
assert.equal(run("contributePlayerCommunity(donor,150000,'청소년 지원','receipt-1').amount"),150000);
const balance=run('donor.community.fund.balance');
assert.equal(run("contributePlayerCommunity(donor,150000,'청소년 지원','receipt-1').id"),run('donor.community.contributions[0].id'));
assert.equal(run('donor.community.fund.balance'),balance,'retry must not debit twice');
assert.equal(run("contributePlayerCommunity(donor,151000,'청소년 지원','receipt-1')"),null,'conflicting retries must be rejected');
assert.equal(run("contributePlayerCommunity(donor,999999999,'청소년 지원','overspend')"),null);
assert.equal(run("contributePlayerCommunity(donor,-5000,'청소년 지원','negative')"),null);
assert.equal(run("contributePlayerCommunity(donor,1000,'','missing-recipient')"),null);
run(`donor.community=JSON.parse(JSON.stringify(donor.community));`);
assert.equal(run("contributePlayerCommunity(donor,150000,'청소년 지원','receipt-1').amount"),150000,'reload keeps idempotency');
assert.equal(run('donor.salary'),100000000);
assert.equal(run('state.teams.find(t=>t.id===donor.teamId).budget'),run('originalBudget'),'donations never debit club money');
run(`state.day=60;contributePlayerCommunity(donor,150000,'청소년 지원','receipt-2');state.day=91;contributePlayerCommunity(donor,150000,'지역 가족 지원','receipt-3');`);
assert.equal(run('donor.community.contributions.length'),3);
assert.equal(run('kpblCommunityAwardCandidate(donor,2030).months'),3);
const panel=run('playerCommunityPanel(donor)');
assert.match(panel,/사회공헌 활동/);
assert.match(panel,/청소년 지원/);
assert.match(panel,/지급 확인/);
const serialized=run('JSON.stringify(donor.community)');
run('playerCommunityPanel(donor)');
assert.equal(run('JSON.stringify(donor.community)'),serialized,'rendering does not create or alter money');
run(`var retired=donors[1];retired.retired=true;`);
assert.equal(run('kpblCommunityAccount(retired)'),null);
assert.equal(run("contributePlayerCommunity(retired,1000,'청소년 지원','retired')"),null);
run(`var flagged=donors[2];flagged.community=structuredClone(donor.community);flagged.community.contributions.forEach(r=>{r.playerId=flagged.id;r.id='flagged:'+r.id;});state.leagueOffice.governance.cases.push({id:'public-case',playerId:flagged.id,type:'doping',year:2030,status:'조사',decision:0});`);
assert.equal(run('kpblCommunityAwardCandidate(flagged,2030)'),null,'unresolved serious public cases defer awards');
run(`state.leagueOffice.governance.cases[0].status='복귀';state.leagueOffice.governance.cases[0].decision=80;state.leagueOffice.governance.cases[0].finalYear=2030;state.leagueOffice.governance.cases[0].remaining=0;`);
assert.equal(run('kpblCommunityAwardCandidate(flagged,2030)'),null,'served current-year conviction still bars award');
run(`state.leagueOffice.governance.cases[0].status='종결';state.leagueOffice.governance.cases[0].decision=0;`);
assert.ok(run('kpblCommunityAwardCandidate(flagged,2030)'),'exoneration restores eligibility');
run(`state.leagueOffice.governance.cases[0].status='조사';var oneOff=donors[3];state.day=1;kpblCommunityAccount(oneOff);state.day=100;contributePlayerCommunity(oneOff,500000,'지역 가족 지원','single-large-payment');`);
assert.equal(run('kpblCommunityAwardCandidate(oneOff,2030)'),null,'one large donation does not meet sustained activity criterion');
assert.equal(run('reviewCommunityAwards(2030)'),null,'no awards before the season review date');
run('state.day=319');
assert.equal(run('reviewCommunityAwards(2030).winnerId'),run('donor.id'));
assert.equal(run('state.leagueOffice.governance.communityAwards.length'),1,'one league winner');
assert.equal(run('donor.community.awards.length'),1);
assert.equal(run('state.awards.length'),0,'charity awards never change athletic awards or Hall of Fame scores');
const articles=run('state.clubNotices.length');
run('reviewCommunityAwards(2030);kpblCommunityDay();reviewCommunityAwards(2030)');
assert.equal(run('donor.community.awards.length'),1);
assert.equal(run('state.clubNotices.length'),articles,'review retries produce no repeated articles');
run(`state.day=1;state.year=2031;state.seasonStartDate='2031-01-01';var voluntary=donors[4];voluntary.profile.trait='팀워크 중심형';delete voluntary.community;kpblCommunityPledge(voluntary);state.day=32;kpblCommunityDay();`);
assert.equal(run('voluntary.community.contributions.length'),1,'monthly player commitment makes an actual funded payment');
run('kpblCommunityDay()');
assert.equal(run('voluntary.community.contributions.length'),1,'monthly call is idempotent');
run(`voluntary.conduct={finances:{debt:1000}};state.day=60;kpblCommunityDay();`);
assert.equal(run('voluntary.community.contributions.length'),1,'indebted players do not take new automatic charity commitments');
run(`state.day=91;kpblCommunityDay();`);
assert.ok(run("state.clubNotices.some(n=>n.communityReport?.receiptIds?.some(id=>id===voluntary.community.contributions[0].id))"),'quarterly public reports refer to actual paid receipts');
console.log('community awards: passed');
