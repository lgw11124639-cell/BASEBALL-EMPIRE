const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const start=source.indexOf('function faCompensationTransfer(');
const end=source.indexOf('function recordPlayerRelease(',start);
assert.ok(start>=0&&end>start,'FA compensation function exists');
const state={year:2026,day:350,teams:[{budget:0},{budget:0}],faCompensations:[]};
const notices=[];
let failRecipient=false;
const financeTeam=id=>state.teams[id]||null;
const financeEntry=(id,amount)=>{const t=financeTeam(id);if(!t||t.budget+amount<0||(id===0&&failRecipient))return false;t.budget+=amount;return true};
const context=vm.createContext({state,Math,Number,financeTeam,financeEntry,clubNotice:(...args)=>notices.push(args),money:n=>String(n)});
vm.runInContext(source.slice(start,end),context);
const settle=()=>vm.runInContext("faCompensationTransfer({id:7,name:'Test'},0,1,'B',40000000)",context);
state.teams[1].budget=50000000;
assert.equal(settle(),false,'insufficient funds rejected');
assert.equal(state.teams[0].budget,0);
assert.equal(state.teams[1].budget,50000000);
assert.equal(state.faCompensations.length,0);
state.teams[1].budget=100000000;
failRecipient=true;
assert.equal(settle(),false,'recipient credit failure rejected');
assert.equal(state.teams[1].budget,100000000,'payer refunded');
assert.equal(state.faCompensations.length,0,'failed payment not recorded');
failRecipient=false;
assert.equal(settle(),true,'successful settlement');
assert.equal(state.teams[0].budget,80000000,'old club receives compensation');
assert.equal(state.teams[1].budget,20000000,'new club pays compensation');
assert.equal(state.faCompensations.length,1,'one completed compensation record');
assert.equal(notices.length,1,'one successful notice');
console.log('FA compensation insufficient funds, refund and success: PASS');
