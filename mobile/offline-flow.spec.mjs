import {test,expect} from '@playwright/test';
test('local game creation, real day, reload, backup and offline continuation without cloud requests',async({page,context})=>{
 const external=[],errors=[];
 page.on('request',req=>{if(/^https?:/.test(req.url())&&!req.url().startsWith('http://127.0.0.1:4173/'))external.push(req.url());});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',dialog=>dialog.accept());
 await page.goto('/');await expect(page.getByRole('button',{name:'새 게임하기',exact:true})).toBeVisible();
 await expect(page.locator('.start-foot')).toContainText('이 기기에 자동 저장');
 await page.getByRole('button',{name:'새 게임하기',exact:true}).click();await page.getByRole('button',{name:'새 리그 시작',exact:true}).click();
 await expect(page.locator('#advance-day')).toBeVisible({timeout:60000});
 await page.locator('#advance-day').click();await expect(page.locator('#advance-day')).toBeEnabled({timeout:60000});
 const first=await page.evaluate(()=>window.beOfflineSaveTiming);expect(first.changedParts).toBeGreaterThan(0);
 const snapshot=await page.evaluate(async()=>{const db=await new Promise((ok,no)=>{const r=indexedDB.open('baseball-empire-mobile-v1',1);r.onsuccess=()=>ok(r.result);r.onerror=()=>no(r.error);});return new Promise(ok=>{const tx=db.transaction('records'),s=tx.objectStore('records'),r=s.get('head');r.onsuccess=()=>{const head=r.result,day=head.current.entries.find(e=>e.field==='day'),q=s.get(day.key);q.onsuccess=()=>ok({day:JSON.parse(q.result),revision:head.revision});};tx.oncomplete=()=>db.close();});});
 expect(snapshot.day).toBe(2);
 await page.reload();await expect(page.getByRole('button',{name:'이어하기 · 불러오기',exact:true})).toBeEnabled();await page.getByRole('button',{name:'이어하기 · 불러오기',exact:true}).click();
 await expect(page.locator('#advance-day')).toBeVisible();
 await page.locator('.save-section summary').click();
 const downloadEvent=page.waitForEvent('download');await page.locator('#backup').click();const download=await downloadEvent;expect(download.suggestedFilename()).toContain('-2.json');
 const backupPath=await download.path();expect(backupPath).toBeTruthy();
 await context.setOffline(true);await page.locator('#advance-day').click();await expect(page.locator('#advance-day')).toBeEnabled({timeout:60000});
 expect(await page.evaluate(()=>window.beOfflineMobile)).toBe(true);
 await context.setOffline(false);
 await page.locator('#restore').setInputFiles(backupPath);
 await expect(page.locator('.game-header')).toContainText('2027년 1월 2일');
 await page.reload();await page.getByRole('button',{name:'이어하기 · 불러오기',exact:true}).click();
 await expect(page.locator('.game-header')).toContainText('2027년 1월 2일');
 await page.screenshot({path:'test-results/mobile-offline-home.png',fullPage:true});
 expect(external).toEqual([]);expect(errors).toEqual([]);
});
