import {isNativeSave,restoreNativeSave} from '../native-save.js';
import {createNativeSaveCodec,nativeWireDelta,nativeDeltaDigest} from './native-save-codec.mjs';
import {buildWireDelta} from './wire-delta.mjs';
import {runOriginalEngineDay} from './original-engine-day.mjs';
// userId must come from the existing authenticated session, never the body.
// restoreSave must restore a detached full state; store.commit is atomic.
export function createAdvanceDayService({store,restoreSave,encodeSave=async s=>s,runDay=runOriginalEngineDay,fingerprint=()=>'day',codecFactory=null,includeDelta=false,ownsRestoredState=false,stateCache=null,precompute=null}){
 if(!store||typeof restoreSave!=='function')throw Error('Advance-day dependencies missing');
 const active=new Map();
 return async function advance({userId,slot='main',requestId,expectedRev,operation,nativeWire=false,compactWire=false}){
  if(!Number.isSafeInteger(userId)||userId<1)return {status:401,error:'unauthorized'};
  if(slot!=='main'||typeof requestId!=='string'||!/^[-a-zA-Z0-9_]{16,128}$/.test(requestId)||!Number.isSafeInteger(expectedRev)||expectedRev<1)return {status:400,error:'invalid advance request'};
  let requestFingerprint;
  try{requestFingerprint=fingerprint(operation)}catch{return {status:400,error:'invalid operation'}}
  const verifyReceipt=response=>response.status===200&&(response.day?.requestFingerprint??'day')!==requestFingerprint?{status:409,error:'request ID reused for a different operation'}:response;
  const replay=store.receipt(userId,slot,requestId,expectedRev);
  if(replay)return verifyReceipt(replay);
  const key=JSON.stringify([userId,slot]),pending=active.get(key);
  if(pending){
   if(pending.requestId===requestId&&pending.expectedRev===expectedRev&&pending.requestFingerprint===requestFingerprint)return pending.promise;
   return {status:409,error:'day advance in progress'};
  }
  // Defer execution so active is populated before any asynchronous dependency.
  const promise=Promise.resolve().then(async()=>{
   let failurePhase='load';
   try{
    const timing={},started=performance.now();
    let phase=started;const mark=name=>{const now=performance.now();timing[name]=Math.round(now-phase);phase=now};
    const meta=(stateCache||precompute)&&typeof store.metadata==='function'?store.metadata(userId,slot):null;
    if(precompute&&nativeWire&&!operation&&meta){
     if(meta.rev!==expectedRev)return {status:409,error:'revision conflict',current_rev:meta.rev};
     let prepared=null;try{
      prepared=compactWire?precompute.getFast?.(userId,slot,expectedRev,meta.digest):null;
      if(!prepared&&!compactWire)prepared=precompute.get(userId,slot,expectedRev,meta.digest);
      if(!prepared){const waiting=performance.now();prepared=await precompute.wait?.(userId,slot,expectedRev,meta.digest);timing.prepareWaitMs=Math.round(performance.now()-waiting);if(prepared&&compactWire)prepared=precompute.getFast?.(userId,slot,expectedRev,meta.digest)||prepared}
     }catch{precompute.invalidate(userId,slot)}
     if(prepared){
      const fast=compactWire&&prepared.shards&&prepared.delta;
      // Fast artifacts are generated by the same versioned worker, gzip-CRC
      // checked on read, and bound to user/revision/input digest by the queue.
      if(fast){
       const keys=prepared.shards.map(([key])=>key),changes=[...Object.keys(prepared.delta.set),...Object.keys(prepared.delta.patches)];
       if(!/^[a-f0-9]{64}$/.test(prepared.nextDigest)||new Set(keys).size!==keys.length||keys.length!==changes.length||[...keys,...prepared.delta.unset].some(key=>typeof key!=='string'||['__proto__','constructor','prototype'].includes(key))||keys.some(key=>!changes.includes(key)))throw Error('Invalid prepared field set');
      }
      mark('loadMs');timing.loadMs=Math.max(0,timing.loadMs-(timing.prepareWaitMs||0));const serializedDelta=new Map(prepared.set||[]),unset=fast?prepared.delta.unset:prepared.unset;
      if(!fast&&nativeDeltaDigest(meta.digest,expectedRev+1,serializedDelta,unset)!==prepared.nextDigest){precompute.invalidate(userId,slot);throw Error('Prepared day digest mismatch')}
      const set=fast?prepared.delta.set:Object.fromEntries([...serializedDelta].map(([key,raw])=>[key,JSON.parse(raw)]));mark('restoreMs');
      stateCache?.clear();const background=prepared.result.timing;
      Object.assign(timing,{precomputed:true,backgroundEngineMs:background.engineMs,backgroundTotalMs:background.totalMs,engineMs:0,packMs:0,deltaMs:0,cacheMs:0,storageFormat:'server-json-v1',changedFields:fast?prepared.shards.length:serializedDelta.size,totalFields:background.totalFields});
      const memory=process.memoryUsage();timing.memory={rssMiB:Math.round(memory.rss/1048576),heapUsedMiB:Math.round(memory.heapUsed/1048576)};
      const response=verifyReceipt(store.commit({user:userId,slot,requestId,expectedRev,...(fast?{preparedDelta:{shards:prepared.shards,unset,nextDigest:prepared.nextDigest}}:{serializedDelta,delta:{set,unset}}),result:{...prepared.result,requestFingerprint,timing}}));
      if(response.status===200&&!response.replayed){try{precompute.committed(userId,slot,response.rev,response.digest)}catch{}}
      return response.status===200&&!response.replayed&&includeDelta?{...response,wireDelta:{fromRevision:expectedRev,toRevision:response.rev,set,unset,...(fast?{patches:prepared.delta.patches}:{})}}:response;
     }
    }
    const cached=meta?.rev===expectedRev?stateCache?.take(userId,slot,meta.rev,meta.digest):null;
    const snapshot=cached?{...meta,save:cached.wire,fieldHashes:cached.fieldHashes}:store.load(userId,slot);mark('loadMs');
    if(!snapshot)return {status:404,error:'save not found'};
    if(snapshot.rev!==expectedRev)return {status:409,error:'revision conflict',current_rev:snapshot.rev};
    const inputNative=isNativeSave(snapshot.save),native=nativeWire||inputNative;
    timing.nativeMigration=native&&!inputNative;
    timing.inputFormat=inputNative?'server-json-v1':'legacy-gzip';
    const codec=cached?.codec&&((cached.codec.mode==='server-json-v1')===native)?cached.codec:native?createNativeSaveCodec():codecFactory?.();
    failurePhase='restore';let state;
    if(cached?.state&&native&&ownsRestoredState){state=cached.state;timing.cacheHit=true;timing.cacheMode='native-owned-archives'}else if(cached?.serializedFields){
     // Cache immutable JSON bytes, never a mutable native world. Each operation
     // parses fresh owned values without SQLite I/O, gunzip or a world clone.
     snapshot.save=Object.fromEntries([...cached.serializedFields].map(([key,raw])=>[key,JSON.parse(raw)]));
     state=await codec.restore(snapshot.save,{takeOwnership:ownsRestoredState});timing.cacheHit=true;timing.cacheMode='native-json-bytes';
    }else if(cached){
     try{state=JSON.parse(JSON.stringify(cached.state));timing.cacheHit=true}
     catch{state=await codec.restore(snapshot.save,{takeOwnership:ownsRestoredState&&!!snapshot.fieldHashes});timing.cacheHit=false}
    }else{state=await(codec?codec.restore(snapshot.save,{takeOwnership:ownsRestoredState&&!!snapshot.fieldHashes}):restoreSave(structuredClone(snapshot.save)));timing.cacheHit=false}
    const tracked=native&&inputNative&&ownsRestoredState?codec.track(state,snapshot.save):null;
    mark('restoreMs');
    failurePhase='engine';const outcome=await runDay(state,operation,{takeOwnership:ownsRestoredState,runtime:cached?.runtime,...(tracked?{cloneState:tracked.clone,readArchive:tracked.raw}:{})});timing.engineReused=!!cached?.runtime&&outcome.runtime===cached.runtime;mark('engineMs');
    failurePhase='pack';const wire=await(codec?codec.pack(outcome.state):encodeSave(outcome.state));mark('packMs');
    failurePhase='compare';const delta=native?nativeWireDelta(snapshot.save,wire,snapshot.fieldHashes,codec.reusedFields()):buildWireDelta(snapshot.save,wire);mark('deltaMs');
    timing.storageFormat=native?'server-json-v1':'legacy-gzip';
    timing.changedFields=Object.keys(delta.set).length;timing.removedFields=delta.unset.length;timing.totalFields=Object.keys(wire).length;timing.reusedArchiveFields=codec?.reusedFields?.().size||0;
    failurePhase='normalize';let preparedCache=null;
    if(native&&ownsRestoredState&&stateCache&&!precompute){
     // Finish normalization before committing, so even preparation failures leave
     // the DB untouched. Only computed parts are parsed; archives stay shared.
     const normalized={...wire};for(const [key,raw] of delta.serializedFields)normalized[key]=JSON.parse(raw);
     const normalizedState=restoreNativeSave(normalized,{previousWire:wire,previousState:outcome.state,changedKeys:[...delta.serializedFields.keys()]});
     codec.release();outcome.runtime?.park(normalizedState);preparedCache={state:normalizedState,wire:normalized,codec,fieldHashes:delta.fieldHashes,runtime:outcome.runtime};
    }
    mark('cacheMs');
    failurePhase='response-delta';
    const compact=nativeWire&&compactWire&&includeDelta&&store.compactDelta?store.compactDelta(userId,slot,expectedRev,delta,preparedCache?.wire):null;
    if(compact)timing.responseDelta=compact.metrics;
    mark('wireMs');
    const memory=process.memoryUsage();timing.memory={rssMiB:Math.round(memory.rss/1048576),heapUsedMiB:Math.round(memory.heapUsed/1048576)};
    failurePhase='commit';const commitStarted=performance.now();const response=verifyReceipt(store.commit({user:userId,slot,requestId,expectedRev,state:wire,delta,serializedDelta:delta.serializedSet,result:{...outcome.result,requestFingerprint,timing}}));
    if(response.status===200&&!response.replayed){
     // The durable receipt is written before COMMIT finishes. Report the full
     // request's commit/flush time only in this response, without another write.
     if(response.day?.timing)response.day={...response.day,timing:{...response.day.timing,writeMs:Math.round(performance.now()-commitStarted),serviceMs:Math.round(performance.now()-started)}};
     if(precompute){stateCache?.clear();try{precompute.invalidate(userId,slot);precompute.ensure(userId,slot,response.rev,response.digest)}catch{}}
     else if(preparedCache)stateCache.put({user:userId,slot,rev:response.rev,digest:response.digest,...preparedCache});
     else stateCache?.put({user:userId,slot,rev:response.rev,digest:response.digest,state:native?undefined:outcome.state,wire:native?Object.fromEntries(Object.keys(wire).map(key=>[key,null])):wire,codec,fieldHashes:delta.fieldHashes,serializedFields:delta.serializedFields});
    }
    if(response.status===200&&performance.now()-started>2000)console.info(JSON.stringify({stage:'server-day-performance',...response.day?.timing,enginePhases:response.day?.enginePhases||null}));
    if(response.status===200&&!response.replayed&&includeDelta)return {...response,wireDelta:{fromRevision:expectedRev,toRevision:response.rev,set:compact?.set||delta.set,unset:delta.unset,...(compact?{patches:compact.patches}:{})}};
    return response;
   }catch(error){
    // No save or receipt is committed for decoding, engine or persistence errors.
    console.error(JSON.stringify({stage:'server-day-error',phase:failurePhase,userId,slot,requestId,expectedRev,message:String(error?.message||error).slice(0,2000),stack:String(error?.stack||'').slice(0,5000)}));
    return {status:500,error:'day advance failed; reload server status before retrying'};
   }finally{active.delete(key)}
  });
  active.set(key,{requestId,expectedRev,requestFingerprint,promise});return promise;
 };
}
